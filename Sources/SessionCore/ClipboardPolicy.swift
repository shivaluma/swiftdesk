// Clipboard sharing (0.1.5): the pure rules, separated from NSPasteboard behind `PasteboardAccess` so they are unit
// tested without touching the real clipboard. `ClipboardChannel` drives them during a session.

/// How macOS treats programmatic reads of the general pasteboard by this app (`NSPasteboard.AccessBehavior`, macOS
/// 15.4+). With `.ask` (and `.default`, before the first prompt) reading the clipboard's contents shows "SwiftDesk
/// would like to paste from …"; reading `changeCount` and `types` never does.
public enum PasteboardAccessBehavior: Sendable, Equatable {
    /// macOS before 15.4: no paste privacy prompts.
    case unrestricted
    /// Never asked yet; the first read will ask.
    case `default`
    /// Asks on each programmatic read.
    case ask
    case alwaysAllow
    /// Programmatic reads are refused (System Settings › Privacy & Security › Paste from Other Apps).
    case alwaysDeny

    /// Reading the clipboard's contents may show a system prompt.
    public var mayPrompt: Bool { self == .default || self == .ask }

    /// System Settings › Privacy & Security, at the paste-privacy list where possible. The `Privacy_Pasteboard`
    /// anchor is not documented; an unknown anchor still opens Privacy & Security.
    public static let settingsURL = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")!

    @MainActor
    public static func openSettings() {
        NSWorkspace.shared.open(settingsURL)
    }
}

/// The NSPasteboard operations clipboard sharing needs. Main actor, like AppKit's pasteboard use in the app.
@MainActor
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// Every type on the pasteboard. Metadata only: never triggers the macOS paste prompt.
    var types: [String] { get }
    var accessBehavior: PasteboardAccessBehavior { get }
    /// Reads one representation (this is the read macOS may prompt for).
    func data(forType type: String) -> Data?
    /// Replaces the contents with one item holding `representations`; returns the new change count.
    @discardableResult func write(_ representations: [(type: String, data: Data)]) -> Int
}

/// `NSPasteboard.general` (or another named pasteboard, for tests).
@MainActor
public final class SystemPasteboard: PasteboardAccess {
    private let pasteboard: NSPasteboard

    public init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }
    public var types: [String] { pasteboard.types?.map(\.rawValue) ?? [] }

    public var accessBehavior: PasteboardAccessBehavior {
        guard #available(macOS 15.4, *) else { return .unrestricted }
        switch pasteboard.accessBehavior {
        case .default: return .default
        case .ask: return .ask
        case .alwaysAllow: return .alwaysAllow
        case .alwaysDeny: return .alwaysDeny
        @unknown default: return .ask
        }
    }

    public func data(forType type: String) -> Data? {
        pasteboard.data(forType: NSPasteboard.PasteboardType(type))
    }

    @discardableResult
    public func write(_ representations: [(type: String, data: Data)]) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        for (type, data) in representations { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
}

/// What to do with the local clipboard, and how to turn it into a CLIPBOARD message.
public enum ClipboardPolicy {
    // Markers set by password managers and clipboard tools (nspasteboard.org): never share such content.
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// Written next to content received from the peer, so it is never sent back (in addition to the change count).
    public static let originMarkerType = "com.swiftdesk.remote-clipboard"

    public static let plainTextType = "public.utf8-plain-text"
    public static let rtfType = "public.rtf"
    public static let pngType = "public.png"
    public static let tiffType = "public.tiff"
    public static let urlType = "public.url"
    public static let fileURLType = "public.file-url"

    /// TIFF larger than this is not converted (an uncompressed TIFF can be huge; its PNG would exceed the limit).
    public static let maxTIFFInputBytes = 256 << 20

    static let privateTypes: Set<String> = [concealedType, transientType, autoGeneratedType]
    static let supportedTypes: Set<String> = [plainTextType, rtfType, pngType, tiffType, urlType]

    public enum SkipReason: Sendable, Equatable {
        /// Marked concealed / transient / auto-generated (password managers): skipped silently.
        case privateContent
        /// Content SwiftDesk itself wrote from the peer.
        case fromPeer
        /// Copied files (Finder): not shared (no file transfer).
        case files
        /// No text, RTF, image or URL.
        case unsupported
        /// Every supported representation is over its limit; `bytes` is the largest, `limit` its limit.
        case tooLarge(bytes: Int, limit: Int)
        /// macOS refused to let SwiftDesk read the clipboard.
        case accessDenied
    }

    public enum ReadOutcome: Sendable, Equatable {
        case content(ClipboardContent)
        case skipped(SkipReason)
    }

    /// Decides from the pasteboard's types alone (no content read, so no privacy prompt) whether to read it at all.
    public static func screen(types: [String]) -> SkipReason? {
        let set = Set(types)
        if !set.isDisjoint(with: privateTypes) { return .privateContent }
        if set.contains(originMarkerType) { return .fromPeer }
        if set.contains(fileURLType) { return .files }
        if set.isDisjoint(with: supportedTypes) { return .unsupported }
        return nil
    }

    /// The representations read from the pasteboard (main actor), converted later off the main actor.
    public struct Snapshot: Sendable, Equatable {
        public var plainText: Data?
        public var rtf: Data?
        public var png: Data?
        public var tiff: Data?
        public var url: Data?

        public init(plainText: Data? = nil, rtf: Data? = nil, png: Data? = nil, tiff: Data? = nil, url: Data? = nil) {
            self.plainText = plainText
            self.rtf = rtf
            self.png = png
            self.tiff = tiff
            self.url = url
        }

        public var isEmpty: Bool { plainText == nil && rtf == nil && png == nil && tiff == nil && url == nil }
    }

    /// Reads the supported representations that `types` lists (TIFF only when there is no PNG).
    @MainActor
    public static func snapshot(_ pasteboard: some PasteboardAccess, types: [String]) -> Snapshot {
        let set = Set(types)
        func read(_ type: String) -> Data? { set.contains(type) ? pasteboard.data(forType: type) : nil }
        let png = read(pngType)
        return Snapshot(plainText: read(plainTextType), rtf: read(rtfType), png: png,
                        tiff: png == nil ? read(tiffType) : nil, url: read(urlType))
    }

    /// Builds the message content under the size caps. An oversized representation is left out; if nothing is left
    /// for that reason the outcome is `.tooLarge` (the UI shows a notice). Pure apart from `encodePNG`, which runs
    /// only for TIFF.
    public static func content(from snapshot: Snapshot,
                               encodePNG: (Data) -> Data? = ClipboardPolicy.pngFromTIFF) -> ReadOutcome {
        var items: [ClipboardContent.Item] = []
        var oversized: (bytes: Int, limit: Int)?
        func consider(_ kind: ClipboardContent.Kind, _ data: Data?) {
            guard let data, !data.isEmpty else { return }
            let limit = ClipboardContent.limit(for: kind)
            guard data.count <= limit else {
                if data.count > (oversized?.bytes ?? 0) { oversized = (data.count, limit) }
                return
            }
            let item = ClipboardContent.Item(kind: kind, data: data)
            if ClipboardContent(items: [item]).isWellFormed { items.append(item) }
        }
        consider(.plainText, snapshot.plainText)
        consider(.richText, snapshot.rtf)
        consider(.url, snapshot.url)
        if let png = snapshot.png {
            consider(.png, png)
        } else if let tiff = snapshot.tiff {
            if tiff.count > maxTIFFInputBytes {
                oversized = (tiff.count, ClipboardContent.maxImageBytes)
            } else {
                consider(.png, encodePNG(tiff))
            }
        }
        if !items.isEmpty { return .content(ClipboardContent(items: items)) }
        if let oversized { return .skipped(.tooLarge(bytes: oversized.bytes, limit: oversized.limit)) }
        return .skipped(.unsupported)
    }

    /// TIFF → PNG with ImageIO-backed `NSBitmapImageRep` (thread-safe for this use). nil if it is not an image.
    public static func pngFromTIFF(_ tiff: Data) -> Data? {
        NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    /// The pasteboard representations for received content, plus the origin marker. A URL without plain text also
    /// gets a plain-text copy, so apps that paste only strings still get it.
    public static func representations(for content: ClipboardContent) -> [(type: String, data: Data)] {
        var out: [(type: String, data: Data)] = []
        for item in content.items {
            switch item.kind {
            case .plainText: out.append((plainTextType, item.data))
            case .richText: out.append((rtfType, item.data))
            case .png: out.append((pngType, item.data))
            case .url:
                out.append((urlType, item.data))
                if content.data(for: .plainText) == nil { out.append((plainTextType, item.data)) }
            }
        }
        out.append((originMarkerType, Data([1])))
        return out
    }
}

/// Echo suppression and "what is new" bookkeeping for one side's pasteboard.
///
/// A change is examined once (`shouldExamine`); the change SwiftDesk caused by writing the peer's clipboard is never
/// examined, so content never bounces back to where it came from. `baseline` decides whether the clipboard as it is
/// at session start counts as new: the Viewer starts with none (copy, then focus the stream window and paste, as in
/// other remote-desktop apps), the Host with its current count (what was copied on the Host before the session is
/// not pushed to the Viewer).
public struct ClipboardEchoGuard: Sendable, Equatable {
    public private(set) var lastExamined: Int?
    public private(set) var lastWritten: Int?

    public init(baseline: Int?) {
        lastExamined = baseline
    }

    /// True if `changeCount` is a change not examined yet and not SwiftDesk's own write. Marks it examined.
    public mutating func shouldExamine(changeCount: Int) -> Bool {
        guard changeCount != lastExamined else { return false }
        lastExamined = changeCount
        return changeCount != lastWritten
    }

    /// SwiftDesk wrote the peer's clipboard; the resulting change count is its own.
    public mutating func noteWritten(changeCount: Int) {
        lastWritten = changeCount
        lastExamined = changeCount
    }

    /// Starts over from `baseline` (sharing switched back on), keeping the own-write record.
    public mutating func rebase(_ baseline: Int?) {
        lastExamined = baseline
    }
}
