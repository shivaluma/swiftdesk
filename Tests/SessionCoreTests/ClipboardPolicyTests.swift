/// Clipboard sharing's pure rules (0.1.5): which pasteboard content is never shared, the size caps, TIFF → PNG, the
/// representations written for received content, and echo suppression.
@Suite("Clipboard policy")
struct ClipboardPolicyTests {
    private static let png = ClipboardContent.pngSignature + Data([0, 0, 0, 13]) + Data("IHDR".utf8)

    @Test func passwordManagerContentIsNeverRead() {
        for marker in [ClipboardPolicy.concealedType, ClipboardPolicy.transientType, ClipboardPolicy.autoGeneratedType] {
            #expect(ClipboardPolicy.screen(types: [ClipboardPolicy.plainTextType, marker]) == .privateContent, "\(marker)")
        }
    }

    @Test func screeningUsesTypesOnly() {
        #expect(ClipboardPolicy.screen(types: [ClipboardPolicy.plainTextType]) == nil)
        #expect(ClipboardPolicy.screen(types: [ClipboardPolicy.tiffType]) == nil)
        #expect(ClipboardPolicy.screen(types: [ClipboardPolicy.plainTextType, ClipboardPolicy.originMarkerType]) == .fromPeer)
        #expect(ClipboardPolicy.screen(types: [ClipboardPolicy.fileURLType, ClipboardPolicy.plainTextType,
                                               ClipboardPolicy.tiffType]) == .files)
        #expect(ClipboardPolicy.screen(types: ["com.adobe.pdf"]) == .unsupported)
        #expect(ClipboardPolicy.screen(types: []) == .unsupported)
    }

    @Test func textAndLinksWithinTheLimits() {
        let snapshot = ClipboardPolicy.Snapshot(plainText: Data("hello".utf8), rtf: Data("{\\rtf1 hello}".utf8),
                                                url: Data("https://example.com".utf8))
        guard case .content(let content) = ClipboardPolicy.content(from: snapshot) else {
            Issue.record("expected content"); return
        }
        #expect(content.kinds == [.plainText, .richText, .url])
        #expect(content.isWellFormed)
    }

    @Test func oversizedTextIsSkippedWithItsSize() {
        let big = Data(repeating: 0x61, count: ClipboardContent.maxTextBytes + 10)
        #expect(ClipboardPolicy.content(from: .init(plainText: big))
                == .skipped(.tooLarge(bytes: big.count, limit: ClipboardContent.maxTextBytes)))
        // Exactly at the cap is fine.
        let atCap = Data(repeating: 0x61, count: ClipboardContent.maxTextBytes)
        #expect(ClipboardPolicy.content(from: .init(plainText: atCap))
                == .content(ClipboardContent(items: [.init(kind: .plainText, data: atCap)])))
    }

    @Test func oversizedPartsAreLeftOutWhenSomethingFits() {
        let big = Data(repeating: 0x61, count: ClipboardContent.maxTextBytes + 1)
        let outcome = ClipboardPolicy.content(from: .init(plainText: Data("short".utf8), rtf: big))
        #expect(outcome == .content(ClipboardContent(items: [.init(kind: .plainText, data: Data("short".utf8))])))
    }

    @Test func imageCapAppliesAfterPNGEncoding() {
        var huge = Self.png
        huge.append(Data(count: ClipboardContent.maxImageBytes))
        #expect(ClipboardPolicy.content(from: .init(png: huge))
                == .skipped(.tooLarge(bytes: huge.count, limit: ClipboardContent.maxImageBytes)))
        // A TIFF is judged by the PNG it becomes, not by its own (often much larger) size.
        let tiff = Data(repeating: 1, count: 40 << 20)
        #expect(ClipboardPolicy.content(from: .init(tiff: tiff), encodePNG: { _ in Self.png })
                == .content(ClipboardContent(items: [.init(kind: .png, data: Self.png)])))
        #expect(ClipboardPolicy.content(from: .init(tiff: tiff), encodePNG: { _ in huge })
                == .skipped(.tooLarge(bytes: huge.count, limit: ClipboardContent.maxImageBytes)))
        #expect(ClipboardPolicy.content(from: .init(tiff: tiff), encodePNG: { _ in nil }) == .skipped(.unsupported))
    }

    @Test func realTIFFBecomesAPNG() throws {
        let rep = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 3, bitsPerSample: 8,
                                                samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                                colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let tiff = try #require(rep.tiffRepresentation)
        guard case .content(let content) = ClipboardPolicy.content(from: .init(tiff: tiff)) else {
            Issue.record("expected an image"); return
        }
        let png = try #require(content.data(for: .png))
        #expect(png.starts(with: ClipboardContent.pngSignature))
        #expect(NSBitmapImageRep(data: png)?.pixelsWide == 4)
    }

    @Test func invalidTextIsDropped() {
        #expect(ClipboardPolicy.content(from: .init(plainText: Data([0xFF, 0xFE]))) == .skipped(.unsupported))
        #expect(ClipboardPolicy.content(from: .init(png: Data("not a png".utf8))) == .skipped(.unsupported))
        #expect(ClipboardPolicy.content(from: .init(plainText: Data())) == .skipped(.unsupported))
    }

    @Test func receivedContentIsMarkedAsComingFromThePeer() {
        let content = ClipboardContent(items: [.init(kind: .url, data: Data("https://example.com".utf8))])
        let reps = ClipboardPolicy.representations(for: content)
        let types = reps.map(\.type)
        #expect(types.contains(ClipboardPolicy.urlType))
        #expect(types.contains(ClipboardPolicy.plainTextType), "a lone URL also pastes as text")
        #expect(types.contains(ClipboardPolicy.originMarkerType))
        // What SwiftDesk writes is screened out when it looks at its own pasteboard again.
        #expect(ClipboardPolicy.screen(types: types) == .fromPeer)
    }

    @Test func echoGuard() {
        var host = ClipboardEchoGuard(baseline: 5)
        var results: [Bool] = []
        results.append(host.shouldExamine(changeCount: 5))   // the Host's clipboard from before the session is not new
        results.append(host.shouldExamine(changeCount: 6))
        results.append(host.shouldExamine(changeCount: 6))   // each change is examined once
        host.noteWritten(changeCount: 7)
        results.append(host.shouldExamine(changeCount: 7))   // SwiftDesk's own write never goes back
        results.append(host.shouldExamine(changeCount: 8))
        #expect(results == [false, true, false, false, true])

        var viewer = ClipboardEchoGuard(baseline: nil)
        let first = viewer.shouldExamine(changeCount: 42)    // the Viewer's current clipboard counts (copy, focus, paste)
        viewer.rebase(nil)
        let again = viewer.shouldExamine(changeCount: 42)
        #expect(first && again)
    }

    @Test func accessBehaviorPrompts() {
        #expect(PasteboardAccessBehavior.ask.mayPrompt)
        #expect(PasteboardAccessBehavior.default.mayPrompt)
        #expect(!PasteboardAccessBehavior.alwaysAllow.mayPrompt)
        #expect(!PasteboardAccessBehavior.alwaysDeny.mayPrompt)
        #expect(!PasteboardAccessBehavior.unrestricted.mayPrompt)
    }
}

/// Records what a `ClipboardChannel` sends; side-stream completions are released by the test.
final class FakeClipboardTransport: ClipboardTransport, @unchecked Sendable {
    private let lock = NSLock()
    private var _controls: [ControlMessage] = []
    private var _sides: [ControlMessage] = []
    private var _completions: [@Sendable (Bool) -> Void] = []
    var sideOpen = true

    var controls: [ControlMessage] { lock.withLock { _controls } }
    var sides: [ControlMessage] { lock.withLock { _sides } }
    var sentTexts: [String] {
        sides.compactMap {
            if case .clipboard(let c) = $0 { c.data(for: .plainText).map { String(decoding: $0, as: UTF8.self) } } else { nil }
        }
    }

    func sendControl(_ message: ControlMessage) {
        lock.withLock { _controls.append(message) }
    }

    func sendSide(_ message: ControlMessage, completion: (@Sendable (Bool) -> Void)?) -> Bool {
        lock.withLock {
            guard sideOpen else { return false }
            _sides.append(message)
            _completions.append(completion ?? { _ in })
            return true
        }
    }

    /// The oldest in-flight send left the app.
    func completeNext() {
        let next = lock.withLock { _completions.isEmpty ? nil : _completions.removeFirst() }
        next?(true)
    }
}

@MainActor
@Suite("Clipboard channel")
struct ClipboardChannelTests {
    private func channel(_ pasteboard: FakePasteboard, _ transport: FakeClipboardTransport, host: Bool,
                         enabled: Bool = true, canRead: @escaping @MainActor () -> Bool = { true },
                         status: StatusBox = StatusBox()) -> ClipboardChannel {
        ClipboardChannel(pasteboard: pasteboard, transport: transport, localEnabled: enabled, baselineAtStart: host,
                         pollInterval: .seconds(3600), canReadLocal: canRead) { status.value = $0 }
    }

    @MainActor
    final class StatusBox {
        var value = ClipboardSyncStatus.inactive
    }

    @MainActor
    final class Flag {
        var value = false
    }

    /// Start, peer on, side stream ready.
    private func activate(_ c: ClipboardChannel) {
        c.start()
        c.peerStateChanged(ClipboardState(enabled: true))
        c.sideStreamReady()
    }

    @Test func announcesItsSwitch() {
        let transport = FakeClipboardTransport()
        let c = channel(FakePasteboard(), transport, host: true)
        c.start()
        #expect(transport.controls == [.clipboardState(ClipboardState(enabled: true))])
        c.setLocalEnabled(false)
        c.setLocalEnabled(false)
        #expect(transport.controls.last == .clipboardState(ClipboardState(enabled: false)))
        #expect(transport.controls.count == 2, "only changes are announced")
        c.stop()
    }

    @Test func hostSendsOnlyCopiesMadeDuringTheSession() async {
        let pb = FakePasteboard()
        pb.copy(text: "copied before the session")
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: true)
        activate(c)
        c.checkLocal()
        #expect(pb.reads == 0)
        pb.copy(text: "during")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["during"] })
        c.stop()
    }

    @Test func viewerReadsOnlyWhileTheStreamWindowIsKey() async {
        let pb = FakePasteboard()
        pb.copy(text: "copied locally")
        let transport = FakeClipboardTransport()
        let key = Flag()
        let c = channel(pb, transport, host: false, canRead: { key.value })
        activate(c)
        c.checkLocal()
        #expect(pb.reads == 0, "not even read while the window is in the background")
        key.value = true
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["copied locally"] })
        c.stop()
    }

    @Test func receivedContentIsNotEchoedBack() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let status = StatusBox()
        let c = channel(pb, transport, host: false, status: status)
        activate(c)
        c.received(ClipboardContent(items: [.init(kind: .plainText, data: Data("from the peer".utf8))]))
        #expect(pb.text == "from the peer")
        #expect(status.value.lastTransfer?.direction == .received)
        c.checkLocal()
        #expect(await eventually { !c.isReading })
        #expect(transport.sides.isEmpty)
        #expect(pb.reads == 0)
        c.stop()
    }

    @Test func concealedContentIsNeverReadOrSent() async {
        let pb = FakePasteboard()
        pb.copy([ClipboardPolicy.plainTextType: Data("hunter2".utf8), ClipboardPolicy.concealedType: Data()])
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false)
        activate(c)
        c.checkLocal()
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sides.isEmpty)
        #expect(pb.reads == 0, "a password manager's item is skipped on its types alone")
        c.stop()
    }

    /// A password manager copies between the type screening and the contents reads: what was read is not what was
    /// screened, so it is dropped; the next check sees the concealed marker and skips it.
    @Test func copyBetweenScreeningAndReadIsNotSent() async {
        let pb = FakePasteboard()
        pb.copy(text: "ordinary")
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false)
        pb.beforeNextRead = { [unowned pb] in
            pb.copy([ClipboardPolicy.plainTextType: Data("hunter2".utf8), ClipboardPolicy.concealedType: Data()])
        }
        activate(c)   // the peer's switch arriving checks the clipboard at once
        #expect(pb.reads > 0 && pb.beforeNextRead == nil, "the read ran into the copy")
        #expect(!c.isReading, "the snapshot was discarded")
        c.checkLocal()
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sides.isEmpty)
        pb.copy(text: "next")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["next"] })
        c.stop()
    }

    /// The peer's copy is newer than a local one still waiting behind an in-flight transfer: the waiting one is
    /// dropped instead of overwriting the peer's clipboard afterwards.
    @Test func receivedCopyDropsAWaitingLocalOne() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false)
        activate(c)
        pb.copy(text: "big")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["big"] })
        pb.copy(text: "T")
        c.checkLocal()
        #expect(await eventually { !c.isReading })
        c.received(ClipboardContent(items: [.init(kind: .plainText, data: Data("H".utf8))]))
        transport.completeNext()
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sentTexts == ["big"], "T is older than the peer's H")
        #expect(pb.text == "H")
        c.stop()
    }

    /// Same while the local copy is still being converted off the main actor.
    @Test func receivedCopyDropsALocalOneBeingConverted() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false)
        activate(c)
        pb.copy(text: "T")
        c.checkLocal()
        #expect(c.isReading)
        c.received(ClipboardContent(items: [.init(kind: .plainText, data: Data("H".utf8))]))
        #expect(await eventually { !c.isReading })
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sides.isEmpty)
        #expect(pb.text == "H")
        pb.copy(text: "later")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["later"] })
        c.stop()
    }

    @Test func nothingIsWrittenWhileSwitchedOffHere() {
        let pb = FakePasteboard()
        let c = channel(pb, FakeClipboardTransport(), host: true, enabled: false)
        activate(c)
        c.received(ClipboardContent(items: [.init(kind: .plainText, data: Data("x".utf8))]))
        #expect(pb.writes == 0)
        c.stop()
    }

    @Test func peerSwitchGatesSending() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false)
        c.start()
        c.sideStreamReady()
        pb.copy(text: "waiting")
        c.checkLocal()
        #expect(pb.reads == 0, "the peer has not said it shares")
        c.peerStateChanged(ClipboardState(enabled: true))   // checks right away
        #expect(await eventually { transport.sentTexts == ["waiting"] })
        transport.completeNext()
        c.peerStateChanged(ClipboardState(enabled: false))
        pb.copy(text: "not now")
        c.checkLocal()
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sentTexts == ["waiting"])
        c.stop()
    }

    @Test func hostSwitchedBackOnSendsOnlyNewCopies() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: true, enabled: false)
        activate(c)
        pb.copy(text: "copied while sharing was off")
        c.setLocalEnabled(true)
        try? await Task.sleep(for: .milliseconds(100))
        #expect(transport.sides.isEmpty)
        pb.copy(text: "new")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["new"] })
        c.stop()
    }

    @Test func oneInFlightAndTheLatestCopyWins() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: true)
        activate(c)
        pb.copy(text: "A")
        c.checkLocal()
        #expect(await eventually { transport.sentTexts == ["A"] })
        pb.copy(text: "B")
        c.checkLocal()
        #expect(await eventually { !c.isReading })
        pb.copy(text: "C")
        c.checkLocal()
        #expect(await eventually { !c.isReading })
        #expect(transport.sentTexts == ["A"], "B and C wait while A is in flight")
        transport.completeNext()
        #expect(await eventually { transport.sentTexts == ["A", "C"] }, "B was replaced by the newer C")
        c.stop()
    }

    @Test func waitsForTheSideStream() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        transport.sideOpen = false
        let c = channel(pb, transport, host: true)
        c.start()
        c.peerStateChanged(ClipboardState(enabled: true))
        pb.copy(text: "early")
        c.checkLocal()
        #expect(await eventually { !c.isReading })
        #expect(transport.sides.isEmpty)
        transport.sideOpen = true
        c.sideStreamReady()
        #expect(transport.sentTexts == ["early"])
        c.stop()
    }

    @Test func oversizedCopyShowsANotice() async {
        let pb = FakePasteboard()
        let transport = FakeClipboardTransport()
        let status = StatusBox()
        let c = channel(pb, transport, host: true, status: status)
        activate(c)
        let big = Data(repeating: 0x61, count: ClipboardContent.maxTextBytes + 1)
        pb.copy([ClipboardPolicy.plainTextType: big])
        c.checkLocal()
        #expect(await eventually {
            status.value.notice?.kind == .tooLarge(bytes: big.count, limit: ClipboardContent.maxTextBytes)
        })
        #expect(transport.sides.isEmpty)
        c.stop()
    }

    @Test func copiedFilesAreNotShared() {
        let pb = FakePasteboard()
        pb.copy([ClipboardPolicy.fileURLType: Data("file:///tmp/a".utf8), ClipboardPolicy.plainTextType: Data("a".utf8)])
        let status = StatusBox()
        let c = channel(pb, FakeClipboardTransport(), host: false, status: status)
        activate(c)
        c.checkLocal()
        #expect(status.value.notice?.kind == .filesNotShared)
        #expect(pb.reads == 0)
        c.stop()
    }

    @Test func refusedReadsAreReported() {
        let pb = FakePasteboard()
        pb.refuseReads = true
        pb.copy(text: "blocked")
        let status = StatusBox()
        let transport = FakeClipboardTransport()
        let c = channel(pb, transport, host: false, status: status)
        activate(c)
        c.checkLocal()
        #expect(status.value.accessDenied)
        #expect(status.value.notice?.kind == .accessDenied)
        #expect(transport.sides.isEmpty)
        c.stop()
    }

    @Test func alwaysDenyIsNotEvenTried() {
        let pb = FakePasteboard()
        pb.accessBehavior = .alwaysDeny
        pb.copy(text: "x")
        let status = StatusBox()
        let c = channel(pb, FakeClipboardTransport(), host: false, status: status)
        activate(c)
        c.checkLocal()
        #expect(pb.reads == 0)
        #expect(status.value.accessDenied)
        c.stop()
    }
}
